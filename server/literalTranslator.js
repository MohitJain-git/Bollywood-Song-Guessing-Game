/**
 * Translates a Hinglish verse line word-by-word directly into literal English words
 * in the exact Hindi word order (even if the English grammar sounds broken/literal).
 */
function translateHinglishVerseLiterally(hinglishText = '') {
  if (!hinglishText) return '';

  // Match word tokens and non-word separators so punctuation is preserved
  const parts = hinglishText.split(/([a-zA-Z]+)/);
  const translated = parts.map((part) => {
    if (!/^[a-zA-Z]+$/.test(part)) return part;
    const lower = part.toLowerCase();
    const eng = WORD_DICTIONARY[lower];
    if (!eng) return part;
    if (part[0] === part[0].toUpperCase() && part[0] !== part[0].toLowerCase()) {
      return eng.charAt(0).toUpperCase() + eng.slice(1);
    }
    return eng;
  });

  return translated.join('');
}

